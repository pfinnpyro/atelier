#!/usr/bin/env python3
"""Generates crates/atelier-font/src/data/*.rs from public font tables.

Sources (all freely redistributable), read from ReportLab's copies:
- Encodings: ISO 32000 Annex D (Standard, WinAnsi, MacRoman, MacExpert,
  PDFDoc, Symbol, ZapfDingbats built-in encodings).
- Adobe Glyph List 2.0 (BSD-3-Clause, Adobe).
- Glyph widths of the 14 standard fonts, from Adobe's core AFM files.
- The standard Macintosh glyph order (TrueType 'post' table).
- CFF standard strings and charsets, from Adobe Technical
  Note 5176 (read from fontTools' copy).

Usage: gen_font_data.py   (needs `pip install reportlab fonttools`; output is committed)
"""

import importlib
import os

from reportlab.pdfbase import _fontdata, _glyphlist

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "crates", "atelier-font", "src", "data")
HEADER = "// Generated by tools/gen_font_data.py. Do not edit.\n\n"


def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def encodings():
    names = [
        ("STANDARD", "standard", "StandardEncoding"),
        ("WIN_ANSI", "winansi", "WinAnsiEncoding"),
        ("MAC_ROMAN", "macroman", "MacRomanEncoding"),
        ("MAC_EXPERT", "macexpert", "MacExpertEncoding"),
        ("PDF_DOC", "pdfdoc", "PDFDocEncoding"),
        ("SYMBOL", "symbol", "SymbolEncoding"),
        ("ZAPF_DINGBATS", "zapfdingbats", "ZapfDingbatsEncoding"),
    ]
    out = [HEADER, "//! Built-in single-byte encodings (ISO 32000-2, Annex D).\n\n"]
    for const, mod, attr in names:
        table = getattr(importlib.import_module("reportlab.pdfbase._fontdata_enc_" + mod), attr)
        assert len(table) == 256, (mod, len(table))
        out.append("pub static %s: [Option<&str>; 256] = [\n" % const)
        for name in table:
            out.append("    %s,\n" % ("None" if name is None else "Some(%s)" % rs_str(name)))
        out.append("];\n\n")
    write("encodings.rs", "".join(out))


def glyph_list():
    entries = {}
    for name, cp in _glyphlist._glyphname2unicode.items():
        entries[name] = chr(cp)
    for name, cps in _glyphlist._glyphname2unicodes.items():
        entries[name] = "".join(chr(c) for c in cps)
    out = [HEADER, "//! Adobe Glyph List 2.0: glyph name to Unicode, sorted by name.\n",
           "//! Copyright 2002-2019 Adobe. BSD-3-Clause.\n\n",
           "pub static GLYPH_LIST: &[(&str, &str)] = &[\n"]
    for name in sorted(entries):
        text = "".join("\\u{%x}" % ord(c) for c in entries[name])
        out.append('    (%s, "%s"),\n' % (rs_str(name), text))
    out.append("];\n")
    write("glyphlist.rs", "".join(out))


FONTS = [
    ("Courier", "courier"), ("Courier-Bold", "courierbold"),
    ("Courier-Oblique", "courieroblique"), ("Courier-BoldOblique", "courierboldoblique"),
    ("Helvetica", "helvetica"), ("Helvetica-Bold", "helveticabold"),
    ("Helvetica-Oblique", "helveticaoblique"), ("Helvetica-BoldOblique", "helveticaboldoblique"),
    ("Times-Roman", "timesroman"), ("Times-Bold", "timesbold"),
    ("Times-Italic", "timesitalic"), ("Times-BoldItalic", "timesbolditalic"),
    ("Symbol", "symbol"), ("ZapfDingbats", "zapfdingbats"),
]


def std14():
    out = [HEADER, "//! Glyph widths of the 14 standard fonts, from Adobe's core AFM files.\n\n",
           "use crate::std14::Std14;\n\n",
           "pub static FONTS: [Std14; 14] = [\n"]
    for name, mod in FONTS:
        widths = importlib.import_module("reportlab.pdfbase._fontdata_widths_" + mod).widths
        ascent, descent = _fontdata.ascent_descent[name]
        out.append("    Std14 {\n        name: %s,\n        ascent: %d,\n        descent: %d,\n"
                   % (rs_str(name), ascent, descent))
        out.append("        widths: &[\n")
        for g in sorted(widths):
            out.append("            (%s, %d),\n" % (rs_str(g), widths[g]))
        out.append("        ],\n    },\n")
    out.append("];\n")
    write("std14_widths.rs", "".join(out))


def cff():
    from fontTools import cffLib as c
    strings = c.cffStandardStrings
    sid = {name: i for i, name in enumerate(strings)}
    out = [HEADER, "//! CFF standard data (Adobe Technical Note 5176, appendices A and C).\n\n",
           "pub static STANDARD_STRINGS: [&str; %d] = [\n" % len(strings)]
    for name in strings:
        out.append("    %s,\n" % rs_str(name))
    out.append("];\n\n")
    for const, names in [("EXPERT_CHARSET", c.cffIExpertStrings),
                         ("EXPERT_SUBSET_CHARSET", c.cffExpertSubsetStrings)]:
        out.append("pub static %s: &[u16] = &[\n" % const)
        out.append("".join("    %d,\n" % sid[n] for n in names))
        out.append("];\n\n")
    write("cff_std.rs", "".join(out))


def mac_glyphs():
    from fontTools.ttLib.standardGlyphOrder import standardGlyphOrder
    assert len(standardGlyphOrder) == 258
    out = [HEADER, "//! The 258 standard Macintosh glyph names used by TrueType 'post' tables.\n\n",
           "pub static MAC_GLYPH_NAMES: [&str; 258] = [\n"]
    out.extend("    %s,\n" % rs_str(n) for n in standardGlyphOrder)
    out.append("];\n")
    write("mac_glyphs.rs", "".join(out))


def write(name, text):
    with open(os.path.join(OUT, name), "w") as f:
        f.write(text)


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    encodings()
    glyph_list()
    std14()
    cff()
    mac_glyphs()
    print("wrote", OUT)
